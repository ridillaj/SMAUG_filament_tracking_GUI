# generated by ChatGPT
def progress_bar(current, total, bar_length=30):
    """
    Display an ASCII progress bar in the terminal.

    :param current: Current progress (int)
    :param total: Total value to reach (int)
    :param bar_length: Length of the progress bar in characters
    """
    fraction = current / total
    filled_length = int(bar_length * fraction)
    bar = '█' * filled_length + '-' * (bar_length - filled_length)
    percent = fraction * 100
    # \r returns the cursor to the start of the line
    print(f'\r|{bar}| {percent:6.2f}% Complete', end='')
    if current == total:
        print()  # Move to the next line when done


def compute_distance(pos_a, pos_b):
    dist = [(pos_a[i] - pos_b[i]) ** 2 for i in range(0, len(pos_a))]

    return math.sqrt(np.sum(dist))


