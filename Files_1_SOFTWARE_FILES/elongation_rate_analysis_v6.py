# helper function that runs an iterative RANSAC regression to identify growth and shrinkage periods
# based on code generated by Claude, inspired by MTrack: https://www.nature.com/articles/s41598-018-37767-1#Sec6
def get_ransac_iterative(frames, snake_lengths, min_event_length=5, residual_threshold=None):
    frames = np.array(frames)
    snake_lengths = np.array(snake_lengths)

    # Auto-calculate residual threshold based on data variability if not provided
    if residual_threshold is None:
        residual_threshold = np.std(snake_lengths) * 0.5

    growth_events = []
    shrinkage_events = []

    ##  identify growth events:
    remaining_mask = np.ones(len(frames), dtype=bool)

    # Iteratively identify growth events until no more can be found
    while True:
        # Extract only the points that haven't been assigned to a growth event yet
        remaining_frames = frames[remaining_mask]
        remaining_lengths = snake_lengths[remaining_mask]

        # Stop if too few points remain to form a valid event
        if np.sum(remaining_mask) < min_event_length:
            break

        X = remaining_frames.reshape(-1, 1)
        y = remaining_lengths

        try:
            # RANSAC FIT: Use 2nd order polynomial regularized toward linear
            # This captures "near-linear growth" as described in the excerpt
            poly_ransac = make_pipeline(
                PolynomialFeatures(degree=2),
                linear_model.RANSACRegressor(
                    estimator=linear_model.Ridge(alpha=10.0),
                    min_samples=min_event_length,
                    residual_threshold=residual_threshold,
                    max_trials=1000
                )
            )

            # Fit RANSAC to the remaining data
            poly_ransac.fit(X, y)

            # Extract which points RANSAC identified as inliers
            inlier_mask = poly_ransac.named_steps['ransacregressor'].inlier_mask_

        except Exception as e:
            print(f"RANSAC fitting failed: {e}")
            break

        # map inliers to their original indices
        original_indices = np.where(remaining_mask)[0]
        inlier_indices = original_indices[inlier_mask]

        # get the consecutive groups using a helper function
        consecutive_groups = split_into_consecutive_groups(inlier_indices, snake_lengths)

        # based on MTrack, use the longest of the groups
        # Stop if the largest consecutive group is too small, or if no groups were found
        if len(consecutive_groups) == 0:
            break
        largest_group = max(consecutive_groups, key=len)

        if len(largest_group) < min_event_length:
            break

        # Extract the frame and length values for this group
        event_frames = frames[largest_group]
        event_lengths = snake_lengths[largest_group]

        # check if this is a growth event, then store as a linear model
        if event_lengths[-1] > event_lengths[0]:
            slope, intercept = np.polyfit(event_frames, event_lengths, 1)
            growth_events.append({
                'indices': largest_group,
                'frames': event_frames,
                'lengths': event_lengths,
                'slope': slope,
                'intercept': intercept,
                'start_frame': event_frames[0],
                'end_frame': event_frames[-1],
                'duration': event_frames[-1] - event_frames[0],
            })

        # mark points as unusable for future events
        remaining_mask[largest_group] = False

    ## identify shrinkage events
    # Start fresh, but exclude all points already assigned to growth events
    remaining_mask = np.ones(len(frames), dtype=bool)
    for event in growth_events:
        remaining_mask[event['indices']] = False

    # Same iterative process as growth, but looking for shrinkage
    while True:
        remaining_frames = frames[remaining_mask]
        remaining_lengths = snake_lengths[remaining_mask]

        if np.sum(remaining_mask) < min_event_length:
            break

        X = remaining_frames.reshape(-1, 1)
        y = remaining_lengths

        try:
            # uses a linear model restricted to rapid decline, as in MTrack
            shrink_ransac = linear_model.RANSACRegressor(
                estimator=linear_model.LinearRegression(),
                min_samples=min_event_length,
                residual_threshold=residual_threshold,
                max_trials=1000,
                random_state=42
            )
            shrink_ransac.fit(X, y)
            inlier_mask = shrink_ransac.inlier_mask_

        except Exception as e:
            print(f"RANSAC shrinkage fitting failed: {e}")
            break

        # Map, make groups, then pick the best group
        original_indices = np.where(remaining_mask)[0]
        inlier_indices = original_indices[inlier_mask]
        consecutive_groups = split_into_consecutive_groups(inlier_indices, snake_lengths)

        if len(consecutive_groups) == 0:
            break

        largest_group = max(consecutive_groups, key=len)

        if len(largest_group) < min_event_length:
            break

        event_frames = frames[largest_group]
        event_lengths = snake_lengths[largest_group]

        # check fi this is actually shrinkage
        if event_lengths[-1] < event_lengths[0]:
            slope, intercept = np.polyfit(event_frames, event_lengths, 1)

            shrinkage_events.append({
                'indices': largest_group,
                'frames': event_frames,
                'lengths': event_lengths,
                'slope': slope,
                'intercept': intercept,
                'start_frame': event_frames[0],
                'end_frame': event_frames[-1],
                'duration': event_frames[-1] - event_frames[0],
            })

        remaining_mask[largest_group] = False

    # generate output statistics
    total_growth_time = sum(e['duration'] for e in growth_events)
    total_shrinkage_time = sum(e['duration'] for e in shrinkage_events)

    catastrophe_freq = len(shrinkage_events) / total_growth_time if total_growth_time > 0 else 0
    rescue_freq = len(growth_events) / total_shrinkage_time if total_shrinkage_time > 0 else 0

    return growth_events, shrinkage_events, catastrophe_freq, rescue_freq


# helper function to split groups: helps to create better fitting lines
def split_into_consecutive_groups(indices, lengths):
    if len(indices) == 0:
        return []

    groups = []
    current_group = [indices[0]]

    # Iterate through indices, starting a new group when needed
    for idx in indices[1:]:
        # if there is not a significant change in length or too large a gap, continue the group
        # this helps account for any situations where TSOAX loses or adds a filament
        len_diff = abs(lengths[idx] - lengths[idx - 1])
        if idx <= current_group[-1] + 4 and len_diff < lengths[idx] * 0.3:
            current_group.append(idx)
        else:
            # Gap detected, finalize current group and start a new one
            groups.append(current_group)
            current_group = [idx]

    groups.append(current_group)

    return groups


