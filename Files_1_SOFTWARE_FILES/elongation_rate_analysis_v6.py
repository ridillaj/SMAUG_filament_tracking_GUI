# ChatGPT to find closest value in a list and its index
def closest_value_index(values, target):
    pos = bisect.bisect_left(values, target)

    if pos == 0:
        return values[0], 0
    if pos == len(values):
        return values[-1], len(values) - 1

    before, after = values[pos - 1], values[pos]

    if abs(after - target) < abs(before - target):
        return after, pos
    else:
        return before, pos - 1


