def calculate_r_squared(y, y_fit):
    if len(y) == 0 or len(y_fit) == 0:  # Check for empty arrays
        return float('nan')  # Return NaN for invalid input

    # print("inCalcR2: ", y, y_fit)

    ss_res = np.sum((y - y_fit) ** 2)
    ss_tot = np.sum((y - np.mean(y)) ** 2) if len(y) > 1 else 0  # Avoid division by zero

    if ss_tot == 0:  # Handle cases where total variance is zero
        return 1.0 if ss_res == 0 else 0.0

    return 1 - (ss_res / ss_tot)


